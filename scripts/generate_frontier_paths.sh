#!/usr/bin/env bash
# filepath: scripts/generate_frontier_paths.sh
# 在 repo 根目录运行：./scripts/generate_frontier_paths.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
FRONTIER_DIR="$ROOT/crate/frontier"
OUT="$ROOT/tmp/frontier-paths.toml"

mkdir -p "$(dirname "$OUT")"
echo "# Generated by scripts/generate_frontier_paths.sh" >"$OUT"
echo "# Review before pasting into Cargo.toml" >>"$OUT"
find "$FRONTIER_DIR" -name Cargo.toml | while read -r CARGO_TOML; do
  DIR=$(dirname "$CARGO_TOML")
  # 首选解析 [package] name 字段
  NAME=$(sed -n 's/^[[:space:]]*name[[:space:]]*=[[:space:]]*"\([^"]*\)".*/\1/p' "$CARGO_TOML" | head -n1)
  if [ -z "$NAME" ]; then
    # 兜底：尝试搜索 package.name
    NAME=$(awk '/^\[package\]/{p=1} p && /^name/{gsub(/ /,""); gsub(/"/,"",$0); split($0,a,"="); print a[2]; exit}' "$CARGO_TOML" | tr -d ' ')
  fi
  if [ -n "$NAME" ]; then
    REL=$(python3 - <<PY
import os
print(os.path.relpath("$DIR", "$ROOT"))
PY
)
    echo "$NAME = { path = \"$REL\", default-features = false }" >>"$OUT"
  fi
done

echo "DONE -> $OUT"